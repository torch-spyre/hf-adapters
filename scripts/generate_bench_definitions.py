"""Generate ``benchmarks/hf-models/`` and ``benchmarks/selections.yaml``.

Input: ``tests/model_lists/perf.yaml`` (model lists) and ``perf_bench.yaml``
(cadence, naming). Needs only PyYAML.

    python scripts/generate_bench_definitions.py          # write
    python scripts/generate_bench_definitions.py --check  # exit 1 if stale
    python scripts/generate_bench_definitions.py --prune  # also delete extra files
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PERF_YAML = ROOT / "tests" / "model_lists" / "perf.yaml"
BENCH_YAML = ROOT / "tests" / "model_lists" / "perf_bench.yaml"
OUT_DIR = ROOT / "benchmarks"
SUITE = "hf-models"
SYSTEM = "hf-models-spyre-fp16"

# Existing report vocabulary, kept so the identity inputs stay the same.
CONFIGS = ("full_model", "one_block")
MODES = ("prefill_only", "decode_only", "generate")

# Placeholder: the runner picks its own repeat count per model.
ITERATIONS = 5

HEADER = (
    "# Generated by scripts/generate_bench_definitions.py from "
    "tests/model_lists/perf.yaml; do not edit.\n"
)


def _models(perf: dict, section: str) -> list[str]:
    return [str(m) for m in (perf.get(section) or {}).get("models") or []]


def _name(path: str, names: dict[str, str]) -> str:
    return names.get(path) or path.rsplit("/", 1)[-1].lower()


def _token(value: str) -> str:
    return value.replace("_", "-")


def _case(name: str, config: str, mode: str) -> str:
    return f"{name}/config={_token(config)}/mode={_token(mode)}"


def _benchmark(
    path: str, name: str, tier: str, sched: dict[str, object]
) -> tuple[str, str]:
    notes = [f"    schedule.{k}: {_scalar(v)}" for k, v in sched.items()]
    configs = "\n".join(
        f"        - {{token: {_token(c)}, patch: {{workload: {{layer: {c}}}}}}}"
        for c in CONFIGS
    )
    modes = "\n".join(
        f"        - {{token: {_token(m)}, patch: {{workload: {{flags: {{run_mode: {m}}}}}}}}}"
        for m in MODES
    )
    text = f"""{HEADER}apiVersion: bench/v1alpha1
kind: Benchmark
metadata:
  name: {name}
  annotations:
{chr(10).join(notes)}
spec:
  type: perf
  level: layer
  tier: {tier}
  system: {SYSTEM}
  workload:
    type: kernel/layer
    model: "{path}"
    layer: {CONFIGS[0]}
    flags: {{run_mode: {MODES[0]}}}
    load: {{executor: iterations, iterations: {ITERATIONS}}}
  matrix:
    axes:
      config:
{configs}
      mode:
{modes}
"""
    return f"{SUITE}/{name}.yaml", text


def _scalar(value: object) -> str:
    return f'"{value}"' if not isinstance(value, str) else value


def _selection(name: str, description: str, cases: list[str]) -> str:
    items = "\n".join(f"    - {c}" for c in cases)
    return (
        f"apiVersion: bench/v1alpha1\nkind: Selection\n"
        f'metadata: {{name: {name}, description: "{description}"}}\n'
        f"spec:\n  cases:\n{items}\n"
    )


def build() -> dict[str, str]:
    perf = yaml.safe_load(PERF_YAML.read_text())
    meta = yaml.safe_load(BENCH_YAML.read_text())
    names: dict[str, str] = meta.get("benchmark_names") or {}
    sanity = meta.get("sanity_model")
    sched = meta["schedule"]
    nightly, weekly = _models(perf, "nightly"), _models(perf, "weekly")
    for section, paths in (("nightly", nightly), ("weekly", weekly)):
        dupes = sorted({p for p in paths if paths.count(p) > 1})
        if dupes:
            raise SystemExit(f"perf.yaml {section} lists {', '.join(dupes)} twice")
    if sanity not in weekly + nightly:
        raise SystemExit(f"sanity_model {sanity!r} is not in perf.yaml")

    files: dict[str, str] = {}
    by_name: dict[str, str] = {}
    for section, paths in (("nightly", nightly), ("weekly", weekly)):
        for path in paths:
            name = _name(path, names)
            if by_name.setdefault(name, path) != path:
                raise SystemExit(f"{path} and {by_name[name]} both map to {name!r}")
            if f"{SUITE}/{name}.yaml" in files:
                continue
            tier = "core" if section == "nightly" else "extended"
            if path == sanity:
                tier = "sanity"
            cadence = {**sched[section], **(sched.get("overrides") or {}).get(path, {})}
            rel, text = _benchmark(path, name, tier, cadence)
            files[rel] = text

    def cases(paths: list[str]) -> list[str]:
        return [
            _case(_name(p, names), c, m) for p in paths for c in CONFIGS for m in MODES
        ]

    smoke = _case(_name(sanity, names), CONFIGS[1], MODES[0])
    files["selections.yaml"] = HEADER + "---\n".join(
        [
            _selection("smoke", "one case of the sanity model", [smoke]),
            _selection(
                "hf-models-nightly",
                "perf.yaml nightly section",
                cases(nightly),
            ),
            _selection(
                "hf-models-weekly",
                "perf.yaml weekly section",
                cases(weekly),
            ),
        ]
    )
    return files


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if files are stale")
    ap.add_argument(
        "--prune", action="store_true", help="delete hf-models/*.yaml not generated"
    )
    args = ap.parse_args(argv)
    want = build()
    have = {
        str(p.relative_to(OUT_DIR)): p.read_text()
        for p in (OUT_DIR / SUITE).glob("*.yaml")
    }
    sel = OUT_DIR / "selections.yaml"
    if sel.is_file():
        have["selections.yaml"] = sel.read_text()
    if args.check:
        stale = sorted(
            k for k in want.keys() | have.keys() if want.get(k) != have.get(k)
        )
        if stale:
            print(
                "benchmarks/ is stale versus tests/model_lists/perf.yaml: "
                + ", ".join(stale[:5])
                + (" ..." if len(stale) > 5 else "")
                + "\nrun: python scripts/generate_bench_definitions.py",
                file=sys.stderr,
            )
            return 1
        return 0
    extra = sorted(have.keys() - want.keys())
    if extra and not args.prune:
        print(
            "refusing to overwrite: not generated from perf.yaml: "
            + ", ".join(extra)
            + "\nremove them or pass --prune",
            file=sys.stderr,
        )
        return 1
    for rel in extra:
        (OUT_DIR / rel).unlink()
    for rel, text in want.items():
        path = OUT_DIR / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"wrote {len(want)} files under {OUT_DIR.relative_to(ROOT)}/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
